    private void pesquisarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pesquisarButtonActionPerformed

        int matricula;
        try {
            matricula = Integer.parseInt(matriculaInput.getText().trim());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite apenas números na matrícula.");
            return;
        }

        Aluno aluno = dados.pesquisarAluno(matricula);

        if (aluno == null) {
            resultadoArea.setText("Nenhum aluno encontrado com a matrícula " + matricula + ".");
            return;
        }

        Calendar cal = Calendar.getInstance();
        cal.setTime(aluno.getDataNasc());

        String nascimento = String.format("%02d/%02d/%d",
                cal.get(Calendar.DAY_OF_MONTH),
                cal.get(Calendar.MONTH) + 1,
                cal.get(Calendar.YEAR));

        List<String> linhas = new ArrayList<>();
        linhas.add("Matrícula: " + aluno.getMatricula());
        linhas.add("Nome: " + aluno.getNome());
        linhas.add("Nascimento: " + nascimento);
        linhas.add("CPF: " + aluno.getCPF());
        linhas.add("Telefone: " + aluno.getTelefone());

        resultadoArea.setText(String.join("\n", linhas));
    }//GEN-LAST:event_pesquisarButtonActionPerformed


